    print()
    print(render_stamp_duty_note(state="Karnataka"))
    print()
    print(render_confidentiality())
    print()
    print(render_termination())
    print()
    print(render_signatory_block("Acme Technologies Pvt. Ltd.", "R. Sharma", "Director", cin="U72200MH2015PTC123456"))
